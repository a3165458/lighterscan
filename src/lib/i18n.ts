const TABLES: Record<Lang, Record<MsgKey, string>> = {
  en: EN,
  zh: ZH,
};

export function parseLang(raw: string | undefined | null): Lang {
  if (!raw) return DEFAULT_LANG;
  const v = raw.trim().toLowerCase();
  if (v === "en" || v === "english" || v.startsWith("en-")) return "en";
  if (v === "zh" || v === "cn" || v === "chinese" || v.startsWith("zh")) return "zh";
  return DEFAULT_LANG;
}

export function t(
  lang: Lang,
  key: MsgKey,
  vars?: Record<string, string | number>,
): string {
  const table = TABLES[lang] ?? TABLES[DEFAULT_LANG];
  let out = table[key] ?? TABLES.en[key] ?? String(key);
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.replaceAll(`{${name}}`, String(value));
    }
  }
  return out;
}

export function htmlLang(lang: Lang): string {
  return lang === "zh" ? "zh-CN" : "en";
}
